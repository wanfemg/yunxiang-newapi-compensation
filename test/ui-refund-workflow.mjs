  await page.screenshot({path:'test-results/refund-trend-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);console.log('PASS: explicit query, animated waits, automatic approval, manual fallback, durable batch history and interactive mouse/touch/keyboard trends.');
